"""Lay every sheet over each other: report empty cells and references that don't resolve, then generate Go tables."""
import json, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
sheets = {p.stem: json.loads(p.read_text(encoding="utf-8")) for p in sorted((root / "sheets").glob("*.json"))}
problems = []
for name, s in sheets.items():
    for i, row in enumerate(s["rows"]):
        for col in s["columns"]:
            v = row.get(col)
            if v is None or (isinstance(v, str) and not v.strip()):
                problems.append(f"{name}[{row.get('id', i)}].{col}: empty")
        for k in row:
            if k not in s["columns"]:
                problems.append(f"{name}[{row.get('id', i)}].{k}: not a column")
    ids = [r["id"] for r in s["rows"]]
    if len(ids) != len(set(ids)):
        problems.append(f"{name}: duplicate ids")
game_ids = {r["id"] for r in sheets["games"]["rows"]}
for sheet, col in (("modes", "source"), ("fields", "source"), ("hooks", "game")):
    for r in sheets[sheet]["rows"]:
        if r[col] not in game_ids:
            problems.append(f"{sheet}[{r['id']}].{col}: '{r[col]}' is not a games id")
import os
theme_dir = root / "theme" / "VSRG Hub osu!"
used_ids = set()
for f in theme_dir.rglob("*.lua"):
    import re as _re
    used_ids |= set(_re.findall(r'TW\.(?:has|img|scale|sprite|blank|fallback|hd)\("([a-z_A-Z0-9]+)"[,)]', f.read_text(encoding="utf-8")))
    used_ids |= {pre + "_0" for pre in _re.findall(r'TW\.digits\("([a-z]+)"', f.read_text(encoding="utf-8"))}
theme_ids = {r["id"] for r in sheets["theme_elements"]["rows"]}
for u in sorted(used_ids - theme_ids):
    problems.append(f"theme Lua uses element '{u}' that theme_elements does not define")
for r in sheets["modes"]["rows"]:
    if r["action"] not in ("convert", "mount", "skip"):
        problems.append(f"modes[{r['id']}].action: unknown '{r['action']}'")
if problems:
    print("PREFLIGHT FAILED"); [print(" -", p) for p in problems]; sys.exit(1)
cells = sum(len(s["rows"]) * len(s["columns"]) for s in sheets.values())
print(f"preflight clean: {len(sheets)} sheets, {cells} cells checked")

def q(s): return json.dumps(s, ensure_ascii=False)
out = ["// Code generated by tools/preflight.py from sheets/*.json. DO NOT EDIT.", "package main", "",
       "type GameRow struct{ ID, Name, MeltySlug, Role, ArgFlag, ContentRoot, ContentRootConfig string }", "",
       "var Games = []GameRow{"]
for r in sheets["games"]["rows"]:
    out.append(f"\t{{ID: {q(r['id'])}, Name: {q(r['name'])}, MeltySlug: {q(r['meltySlug'])}, Role: {q(r['role'])}, ArgFlag: {q(r['argFlag'])}, ContentRoot: {q(r['contentRoot'])}, ContentRootConfig: {q(r['contentRootConfig'])}}},")
out += ["}", "", "type ModeRow struct {\n\tID, Source, SourceMode, StepsType, Game, HandledBy, Action string\n\tLanes int\n\tRated bool\n}", "", "var Modes = []ModeRow{"]
for r in sheets["modes"]["rows"]:
    out.append(f"\t{{ID: {q(r['id'])}, Source: {q(r['source'])}, SourceMode: {q(r['sourceMode'])}, StepsType: {q(r['etternaStepsType'])}, Game: {q(r['etternaGame'])}, HandledBy: {q(r['handledBy'])}, Action: {q(r['action'])}, Lanes: {r['lanes']}, Rated: {str(r['rated']).lower()}}},")
out += ["}", "", "type HookRow struct{ ID, Kind, Target, Value, Game string }", "", "var Hooks = []HookRow{"]
for r in sheets["hooks"]["rows"]:
    out.append(f"\t{{ID: {q(r['id'])}, Kind: {q(r['kind'])}, Target: {q(r['target'])}, Value: {q(r['value'])}, Game: {q(r['game'])}}},")
out += ["}", "", "type ThemeElementRow struct{ ID, Candidates, IniKey string }", "", "var ThemeElements = []ThemeElementRow{"]
for r in sheets["theme_elements"]["rows"]:
    out.append(f"\t{{ID: {q(r['id'])}, Candidates: {q(r['candidates'])}, IniKey: {q(r['iniKey'])}}},")
out += ["}", ""]
(root / "cmd/triwheel/sheets_gen.go").write_text("\n".join(out), encoding="utf-8")
print("generated cmd/triwheel/sheets_gen.go")
